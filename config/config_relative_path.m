function rel_path = config_relative_path(abs_path, base_dir)
% CONFIG_RELATIVE_PATH  Inverse of config_resolve_path, for writing config.
%
% Anything written back into system_config.mat should be stored relative to
% the repo root when it lives inside the repo, so the .mat stays portable
% and doesn't carry one machine's absolute paths into everyone else's clone.
%
% Paths outside the repo (network share, external drive) are returned
% unchanged as absolute — relativizing those would be wrong.
%
% Inputs:
%   abs_path - absolute path
%   base_dir - base to relativize against (default: config_repo_root())
%
% Output:
%   rel_path - path relative to base_dir with '/' separators, or the
%              original absolute path if it isn't under base_dir

% Generated by Claude Opus 5 9/14/26


if nargin < 2 || isempty(base_dir)
    base_dir = config_repo_root();
end

if isstring(abs_path)
    abs_path = char(abs_path);
end

if isempty(abs_path)
    rel_path = '';
    return
end

% Normalize both sides the same way before comparing
a = strrep(config_resolve_path(abs_path, base_dir), '\', '/');
b = strrep(config_resolve_path(base_dir,  base_dir), '\', '/');

if ~endsWith(b, '/')
    b = [b '/'];
end

% Windows paths are case-insensitive; POSIX are not
if ispc
    is_under = startsWith(lower(a), lower(b));
else
    is_under = startsWith(a, b);
end

if is_under
    rel_path = a(numel(b)+1:end);
else
    rel_path = strrep(a, '/', filesep);
end

end