function abs_path = config_resolve_path(stored_path, base_dir)
% CONFIG_RESOLVE_PATH  Turn a stored config path into an absolute path.
%
% Paths in system_config.mat are stored relative to the repo root so the
% repository can be cloned anywhere and on any OS. This expands them.
%
% Handles:
%   - Either separator on either platform ('.\data\' and './data/' both work)
%   - Already-absolute paths, which are passed through untouched (a lab
%     storing data on a network share or external drive is legitimate)
%   - '.' and '..' segments, collapsed textually
%   - Empty input, which returns empty (an unset optional path)
%
% Inputs:
%   stored_path - path string from config, relative or absolute
%   base_dir    - base for relative paths (default: config_repo_root())
%
% Output:
%   abs_path    - absolute path using native filesep, no trailing separator
%
% Note: resolution is textual. The path does not need to exist yet, which
% matters because data/root_dir is resolved before the first session
% creates it.

% Generated by Claude Opus 5 9/14/26

if nargin < 2 || isempty(base_dir)
    base_dir = config_repo_root();
end

% Tolerate string objects as well as char
if isstring(stored_path)
    stored_path = char(stored_path);
end

% Empty means "not set" — stays empty rather than collapsing to base_dir
if isempty(stored_path) || all(isspace(stored_path))
    abs_path = '';
    return
end

stored_path = strtrim(stored_path);

if isAbsolutePath(stored_path)
    joined = toSlash(stored_path);
else
    joined = [toSlash(base_dir) '/' toSlash(stored_path)];
end

abs_path = strrep(collapse(joined), '/', filesep);

end

%% ================================================================
%  LOCAL FUNCTIONS
%% ================================================================

function p = toSlash(p)
% Work internally in forward slashes regardless of platform
p = strrep(p, '\', '/');
end

function tf = isAbsolutePath(p)
p  = toSlash(p);
tf = false;
if isempty(p)
    return
end
if startsWith(p, '//')          % UNC share: //server/share
    tf = true;
elseif startsWith(p, '/')       % POSIX absolute
    tf = true;
elseif numel(p) >= 2 && isletter(p(1)) && p(2) == ':'   % Windows drive
    tf = true;
end
end

function out = collapse(p)
% Resolve '.' and '..' segments and squeeze duplicate separators.
% Input and output use '/' separators.

is_unc = startsWith(p, '//');
drive  = '';

if is_unc
    body = p(3:end);
    is_abs = true;
else
    body = p;
    if numel(body) >= 2 && isletter(body(1)) && body(2) == ':'
        drive = body(1:2);
        body  = body(3:end);
    end
    is_abs = startsWith(body, '/');
end

parts = strsplit(body, '/');
kept  = {};

for i = 1:numel(parts)
    seg = parts{i};
    if isempty(seg) || strcmp(seg, '.')
        continue
    end
    if strcmp(seg, '..')
        if ~isempty(kept) && ~strcmp(kept{end}, '..')
            kept(end) = [];            %#ok<AGROW>
        elseif ~is_abs
            kept{end+1} = '..';        %#ok<AGROW>
        end
        % '..' above an absolute root is discarded, matching OS behaviour
        continue
    end
    kept{end+1} = seg;                 %#ok<AGROW>
end

joined = strjoin(kept, '/');

if is_unc
    out = ['//' joined];
elseif is_abs
    out = [drive '/' joined];
else
    out = [drive joined];
end

% A path that collapsed to nothing means the base itself
if isempty(out)
    out = '.';
end

end